"""Build cyberalertx/media/v4/glyphs.json: vector outlines of the few fonts the
editorial renderer sets text in, so images carry text as plain paths (no font
lookup at rasterization, identical output on every machine).

Development-time only; needs fontTools (+brotli for WOFF2), which production
does not install:

    python -m venv /tmp/fv && /tmp/fv/bin/pip install fonttools==4.55.3 brotli==1.1.0
    /tmp/fv/bin/python ops/media/build_glyphs.py <geist-mono-latin.woff2>

Geist Mono ships with Next.js (next/dist/next-devtools/server/font). All fonts
are SIL OFL 1.1; their notices are in cyberalertx/media/v4/fonts/.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont

ROOT = Path(__file__).resolve().parents[2]
CHARS = [chr(c) for c in range(32, 127)] + list("•·—–…°×→←↑↓▲▼●○■□✓✕€£$№")


def extract(font: TTFont) -> dict:
    upm = font["head"].unitsPerEm
    k = 1000 / upm
    cmap, gs = font.getBestCmap(), font.getGlyphSet()
    out: dict[str, list] = {}
    for ch in CHARS:
        name = cmap.get(ord(ch))
        if name is None:
            continue
        pen = SVGPathPen(gs, ntos=lambda v: str(round(v)))
        gs[name].draw(TransformPen(pen, (k, 0, 0, k, 0, 0)))
        out[ch] = [round(gs[name].width * k), pen.getCommands()]
    hhea = font["hhea"]
    return {"upm": 1000, "ascender": round(hhea.ascent * k), "descender": round(hhea.descent * k),
            "cap": round(getattr(font["OS/2"], "sCapHeight", 700) * k), "glyphs": out}


def main(geist_mono: str) -> None:
    fonts = ROOT / "frontend" / "assets" / "fonts"
    spec = {
        "display": (TTFont(fonts / "SpaceGrotesk-SemiBold.ttf"), "Space Grotesk SemiBold"),
        "ui": (TTFont(fonts / "FiraSansCondensed-Medium.ttf"), "Fira Sans Condensed Medium"),
        "ui_bold": (TTFont(fonts / "FiraSansCondensed-SemiBold.ttf"), "Fira Sans Condensed SemiBold"),
    }
    gm = TTFont(geist_mono)
    spec["mono"] = (instantiateVariableFont(gm, {"wght": 450}), "Geist Mono (wght 450)")
    gm2 = TTFont(geist_mono)
    spec["mono_bold"] = (instantiateVariableFont(gm2, {"wght": 650}), "Geist Mono (wght 650)")
    data = {"note": "Generated by ops/media/build_glyphs.py. SIL OFL 1.1 fonts; see fonts/ for notices.",
            "fonts": {k: {"family": fam, **extract(f)} for k, (f, fam) in spec.items()}}
    dst = ROOT / "cyberalertx" / "media" / "v4" / "glyphs.json"
    dst.write_text(json.dumps(data, separators=(",", ":"), ensure_ascii=False), encoding="utf-8")
    print(dst, dst.stat().st_size)


if __name__ == "__main__":
    main(sys.argv[1])
